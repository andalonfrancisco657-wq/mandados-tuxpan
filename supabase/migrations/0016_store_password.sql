-- v28: contraseña de la tienda para la tablet. Hash bcrypt, nunca legible. El código de 6 dígitos queda para activar/recuperar.
create table if not exists private.store_auth(store_id bigint primary key references public.stores(id) on delete cascade,
  pw_hash text, pw_set_at timestamptz, epoch int not null default 0, blocked boolean not null default false);
create table if not exists private.store_pw_fail(store_id bigint references public.stores(id) on delete cascade, uid uuid, fails int not null default 0,
  locked_until timestamptz, primary key(store_id,uid));
create table if not exists private.store_pw_attempt(id bigint generated by default as identity primary key, store_id bigint references public.stores(id) on delete cascade,
  uid uuid, ok boolean, created_at timestamptz not null default now());
create index if not exists store_pw_attempt_store on private.store_pw_attempt(store_id, created_at);
alter table public.profiles add column if not exists tablet_via text, add column if not exists tablet_epoch int not null default 0;

-- sesión de tienda válida: tienda activa, no bloqueada, misma "época" (cerrar sesiones), y código activo (si entró con código) o contraseña vigente
create or replace function private.my_store() returns bigint language sql stable security definer set search_path='' as
$$ select p.store_id from public.profiles p join public.stores s on s.id=p.store_id and s.act
     left join private.store_auth a on a.store_id=p.store_id
   where p.id=(select auth.uid()) and p.role='tienda' and not coalesce(a.blocked,false) and p.tablet_epoch=coalesce(a.epoch,0)
     and ((p.tablet_via='pw' and a.pw_hash is not null)
       or (coalesce(p.tablet_via,'code')='code' and exists(select 1 from public.tablet_codes t where t.id=p.tablet_code_id and t.act and t.store_id=p.store_id))) $$;

-- el código: igual que antes, pero no entra si la tienda está bloqueada; guarda la época
create or replace function public.redeem_tablet_code(p_store bigint, p_code text) returns boolean language plpgsql security definer set search_path='' as $$
declare t public.tablet_codes; me public.profiles; a private.store_auth;
begin
  select * into me from public.profiles where id=auth.uid();
  if me.id is null then raise exception 'Sin sesión'; end if;
  if me.role not in ('cliente','tienda') then raise exception 'Esta cuenta no puede usarse como tablet'; end if;
  select * into a from private.store_auth where store_id=p_store;
  if coalesce(a.blocked,false) or not exists(select 1 from public.stores where id=p_store and act) then raise exception 'Esta tienda está bloqueada. Habla con Mandados Tuxpan'; end if;
  select * into t from public.tablet_codes where store_id=p_store and act order by id desc limit 1 for update;
  if t.id is null then raise exception 'Código incorrecto'; end if;
  if t.locked_until is not null and t.locked_until>now() then raise exception 'Demasiados intentos. Espera un minuto'; end if;
  if p_code !~ '^\d{6}$' or extensions.crypt(p_code, t.code_hash) <> t.code_hash then
    update public.tablet_codes set fails=fails+1, locked_until=case when fails+1>=5 then now()+interval '1 minute' else null end,
      act = act and fails+1 < 30 where id=t.id;
    return false;
  end if;
  update public.tablet_codes set fails=0, locked_until=null, last_used=now() where id=t.id;
  update public.profiles set role='tienda', store_id=p_store, tablet_code_id=t.id, tablet_via='code', tablet_epoch=coalesce(a.epoch,0),
    nombre=(select n from public.stores where id=p_store) where id=me.id;
  perform private.audit('tienda:'||(select n from public.stores where id=p_store),'Tablet: inicio de sesión');
  return true;
end $$;

-- lista para la pantalla de entrada (sin datos sensibles)
create or replace function public.store_login_list() returns jsonb language sql stable security definer set search_path='' as $$
  select coalesce(jsonb_agg(jsonb_build_object('id',s.id,'n',s.n,'cat',s.cat,'pw',a.pw_hash is not null,
     'code',exists(select 1 from public.tablet_codes t where t.store_id=s.id and t.act)) order by s.n),'[]')
  from public.stores s left join private.store_auth a on a.store_id=s.id where s.act and not coalesce(a.blocked,false) $$;

create or replace function public.my_store_auth() returns jsonb language plpgsql stable security definer set search_path='' as $$
declare ms bigint := private.my_store(); a private.store_auth; v text;
begin
  if ms is null then return null; end if;
  select * into a from private.store_auth where store_id=ms; select tablet_via into v from public.profiles where id=auth.uid();
  return jsonb_build_object('store',ms,'hasPw',a.pw_hash is not null,'via',coalesce(v,'code'));
end $$;

create or replace function public.set_store_password(p_new text, p_current text default null) returns jsonb language plpgsql security definer set search_path='' as $$
declare ms bigint := private.my_store(); a private.store_auth; v text; sn text;
begin
  if ms is null then raise exception 'Entra primero con el código o la contraseña de la tienda'; end if;
  if length(coalesce(p_new,''))<8 then raise exception 'La contraseña debe tener al menos 8 caracteres'; end if;
  if length(p_new)>72 then raise exception 'La contraseña es demasiado larga'; end if;
  insert into private.store_auth(store_id) values(ms) on conflict do nothing;
  select * into a from private.store_auth where store_id=ms for update; select tablet_via into v from public.profiles where id=auth.uid();
  -- con contraseña ya creada: desde una sesión de contraseña se pide la actual; desde el código (recuperación) no
  if a.pw_hash is not null and coalesce(v,'code')='pw' then
    if p_current is null or extensions.crypt(p_current,a.pw_hash)<>a.pw_hash then raise exception 'La contraseña actual no es correcta'; end if;
  end if;
  update private.store_auth set pw_hash=extensions.crypt(p_new, extensions.gen_salt('bf',10)), pw_set_at=now() where store_id=ms;
  update public.profiles set tablet_via='pw', tablet_epoch=a.epoch where id=auth.uid();
  select s.n into sn from public.stores s where s.id=ms;
  perform private.audit('tienda:'||sn, case when a.pw_hash is null then 'Tablet: contraseña creada' else 'Tablet: contraseña cambiada' end);
  return public.my_store_auth();
end $$;

create or replace function public.login_store_password(p_store bigint, p_pw text) returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid := auth.uid(); me public.profiles; a private.store_auth; f private.store_pw_fail; s public.stores; g int;
begin
  select * into me from public.profiles where id=u;
  if me.id is null then raise exception 'Sin sesión'; end if;
  if me.role not in ('cliente','tienda') then raise exception 'Esta cuenta no puede usarse como tablet'; end if;
  select * into s from public.stores where id=p_store; select * into a from private.store_auth where store_id=p_store;
  if s.id is null or not s.act or coalesce(a.blocked,false) then return jsonb_build_object('ok',false,'msg','Esta tienda está bloqueada. Habla con Mandados Tuxpan'); end if;
  if a.pw_hash is null then return jsonb_build_object('ok',false,'msg','Esta tienda aún no tiene contraseña: entra con el código de activación'); end if;
  select * into f from private.store_pw_fail where store_id=p_store and uid=u;
  if f.locked_until is not null and f.locked_until>now() then
    return jsonb_build_object('ok',false,'msg','Demasiados intentos. Espera '||ceil(extract(epoch from f.locked_until-now())/60)||' min o entra con el código de activación'); end if;
  select count(*) into g from private.store_pw_attempt where store_id=p_store and not ok and created_at>now()-interval '15 minutes';
  if g>=20 then return jsonb_build_object('ok',false,'msg','Demasiados intentos en esta tienda. Espera 15 minutos o entra con el código de activación'); end if;
  if extensions.crypt(coalesce(p_pw,''),a.pw_hash)<>a.pw_hash then
    insert into private.store_pw_attempt(store_id,uid,ok) values(p_store,u,false);
    insert into private.store_pw_fail(store_id,uid,fails) values(p_store,u,1)
      on conflict (store_id,uid) do update set fails=case when private.store_pw_fail.locked_until is not null and private.store_pw_fail.locked_until<=now() then 1 else private.store_pw_fail.fails+1 end,
        locked_until=case when (case when private.store_pw_fail.locked_until is not null and private.store_pw_fail.locked_until<=now() then 1 else private.store_pw_fail.fails+1 end)>=5 then now()+interval '5 minutes' else null end
      returning * into f;
    if f.locked_until is not null then perform private.audit('tienda:'||s.n,'Tablet: bloqueo por contraseña incorrecta','5 intentos fallidos · 5 min'); end if;
    return jsonb_build_object('ok',false,'msg',case when f.locked_until is not null then 'Contraseña incorrecta. Se bloqueó 5 minutos.' else 'Contraseña incorrecta. Te quedan '||(5-f.fails)||' intentos.' end);
  end if;
  insert into private.store_pw_attempt(store_id,uid,ok) values(p_store,u,true);
  delete from private.store_pw_fail where store_id=p_store and uid=u;
  update public.profiles set role='tienda', store_id=p_store, tablet_code_id=null, tablet_via='pw', tablet_epoch=a.epoch, nombre=s.n where id=u;
  perform private.audit('tienda:'||s.n,'Tablet: inicio de sesión con contraseña');
  return jsonb_build_object('ok',true);
end $$;

-- controles del dueño/directivo
create or replace function public.store_auth_admin() returns jsonb language plpgsql stable security definer set search_path='' as $$
begin
  if not private.is_admin() then raise exception 'Sin permiso'; end if;
  return coalesce((select jsonb_object_agg(s.id::text, jsonb_build_object('hasPw',a.pw_hash is not null,'pwT',(extract(epoch from a.pw_set_at)*1000)::bigint,'blocked',coalesce(a.blocked,false),
     'ses',(select count(*) from public.profiles p where p.role='tienda' and p.store_id=s.id and p.tablet_epoch=coalesce(a.epoch,0))))
    from public.stores s left join private.store_auth a on a.store_id=s.id),'{}');
end $$;
create or replace function public.store_auth_action(p_store bigint, p_action text) returns jsonb language plpgsql security definer set search_path='' as $$
declare s public.stores;
begin
  if not private.is_admin() then raise exception 'Solo dueño o directivo'; end if;
  select * into s from public.stores where id=p_store; if s.id is null then raise exception 'Tienda no existe'; end if;
  insert into private.store_auth(store_id) values(p_store) on conflict do nothing;
  if p_action='reset_pw' then
    update private.store_auth set pw_hash=null, pw_set_at=null, epoch=epoch+1 where store_id=p_store;
    update public.tablet_codes set act=false where store_id=p_store;
    perform private.audit('tienda:'||s.n,'Contraseña de la tablet restablecida','Se cerraron las sesiones; la tienda debe entrar con un código nuevo');
  elsif p_action='close_sessions' then
    update private.store_auth set epoch=epoch+1 where store_id=p_store;
    perform private.audit('tienda:'||s.n,'Sesiones de la tablet cerradas');
  elsif p_action in ('block','unblock') then
    update private.store_auth set blocked=(p_action='block'), epoch=epoch+case when p_action='block' then 1 else 0 end where store_id=p_store;
    perform private.audit('tienda:'||s.n,case when p_action='block' then 'Tablet bloqueada' else 'Tablet desbloqueada' end);
  else raise exception 'Acción no válida'; end if;
  return public.store_auth_admin();
end $$;
revoke all on function public.store_login_list(), public.my_store_auth(), public.set_store_password(text,text), public.login_store_password(bigint,text),
  public.store_auth_admin(), public.store_auth_action(bigint,text) from public, anon;
grant execute on function public.store_login_list() to anon, authenticated;
grant execute on function public.my_store_auth(), public.set_store_password(text,text), public.login_store_password(bigint,text),
  public.store_auth_admin(), public.store_auth_action(bigint,text) to authenticated;
