-- Solicitudes de activación de tiendas (desde la tablet, con sesión anónima)
create table public.store_activation_requests(
  id bigint generated by default as identity primary key,
  session_id uuid references auth.users(id) on delete set null,
  nombre text not null, tipo text not null check (tipo in ('abarrotes','farmacia','conveniencia','otro')),
  direccion text not null, encargado text not null, tel text not null, notas text not null default '',
  status text not null default 'pendiente' check (status in ('pendiente','aprobada','rechazada')),
  motivo text not null default '', store_id bigint references public.stores(id) on delete set null,
  reviewed_by uuid references auth.users(id) on delete set null, reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create index on public.store_activation_requests(session_id); create index on public.store_activation_requests(tel);
create index on public.store_activation_requests(store_id); create index on public.store_activation_requests(reviewed_by);
alter table public.store_activation_requests enable row level security;
revoke all on public.store_activation_requests from anon, authenticated;
grant select on public.store_activation_requests to authenticated;
create policy sreq_admin_sel on public.store_activation_requests for select to authenticated using ((select private.is_admin()));

create or replace function public.request_store_activation(p jsonb) returns bigint language plpgsql security definer set search_path='' as $$
declare u uuid := auth.uid(); t text := regexp_replace(coalesce(p->>'tel',''),'\D','','g'); r text := private.my_role(); nid bigint;
begin
  if u is null then raise exception 'Sin sesión'; end if;
  if r not in ('cliente','tienda') then raise exception 'Esta cuenta no puede enviar solicitudes'; end if;
  if length(trim(coalesce(p->>'nombre','')))<3 then raise exception 'Escribe el nombre de la tienda'; end if;
  if coalesce(p->>'tipo','') not in ('abarrotes','farmacia','conveniencia','otro') then raise exception 'Elige el tipo de tienda'; end if;
  if length(trim(coalesce(p->>'direccion','')))<5 then raise exception 'Escribe la dirección'; end if;
  if length(trim(coalesce(p->>'encargado','')))<3 then raise exception 'Escribe el nombre del encargado'; end if;
  if length(t)<>10 then raise exception 'El teléfono debe tener 10 dígitos'; end if;
  if (select count(*) from public.store_activation_requests where session_id=u and created_at>now()-interval '1 day')>=3
     or (select count(*) from public.store_activation_requests where tel=t and created_at>now()-interval '1 day')>=3
     or (select count(*) from public.store_activation_requests where created_at>now()-interval '1 hour')>=60 then
    raise exception 'Ya enviaste varias solicitudes hoy. Espera a que el Dueño te contacte'; end if;
  insert into public.store_activation_requests(session_id,nombre,tipo,direccion,encargado,tel,notas)
  values(u,left(trim(p->>'nombre'),100),p->>'tipo',left(trim(p->>'direccion'),300),left(trim(p->>'encargado'),100),t,left(trim(coalesce(p->>'notas','')),500))
  returning id into nid;
  return nid;
end $$;

create or replace function public.my_store_requests() returns jsonb language sql stable security definer set search_path='' as $$
  select coalesce(jsonb_agg(jsonb_build_object('id',id,'nombre',nombre,'status',status,'motivo',motivo,'t',(extract(epoch from created_at)*1000)::bigint) order by id desc),'[]')
  from public.store_activation_requests where session_id=(select auth.uid())
$$;

create or replace function public.review_store_request(p_id bigint, p_approve boolean, p_motivo text default '') returns bigint language plpgsql security definer set search_path='' as $$
declare q public.store_activation_requests; sid bigint;
begin
  if not private.is_admin() then raise exception 'Solo dueño o directivo'; end if;
  select * into q from public.store_activation_requests where id=p_id for update;
  if q.id is null then raise exception 'Solicitud no existe'; end if;
  if q.status<>'pendiente' then raise exception 'La solicitud ya fue revisada'; end if;
  if p_approve then
    insert into public.stores(cat,n,tipo,col,hor,act,ej,extra) values(case when q.tipo='farmacia' then 'farmacia' else 'abarrotes' end, q.nombre,
      case q.tipo when 'abarrotes' then 'Tienda de abarrotes' when 'farmacia' then 'Farmacia' when 'conveniencia' then 'Tienda de conveniencia' else 'Otro' end,
      q.direccion,'',true,false,jsonb_build_object('revT',null,'revPor','','solId',q.id))
    returning id into sid;
    update public.store_activation_requests set status='aprobada',store_id=sid,reviewed_by=auth.uid(),reviewed_at=now() where id=p_id;
    perform private.audit('tienda:'||q.nombre,'Solicitud de activación aprobada');
  else
    update public.store_activation_requests set status='rechazada',motivo=left(coalesce(p_motivo,''),300),reviewed_by=auth.uid(),reviewed_at=now() where id=p_id;
    perform private.audit('tienda:'||q.nombre,'Solicitud de activación rechazada',coalesce(p_motivo,''));
  end if;
  return sid;
end $$;
revoke all on function public.request_store_activation(jsonb), public.my_store_requests(), public.review_store_request(bigint,boolean,text) from public, anon;
grant execute on function public.request_store_activation(jsonb), public.my_store_requests(), public.review_store_request(bigint,boolean,text) to authenticated;
alter publication supabase_realtime add table public.store_activation_requests;
