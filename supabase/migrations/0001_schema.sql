-- Mandados Tuxpan · esquema base (fase 1)
create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

-- ===== perfiles y roles =====
create table public.profiles(
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'cliente' check (role in ('cliente','repartidor','dueno','directivo','tienda')),
  nombre text not null default '',
  email text,
  tel text,
  store_id bigint,
  tablet_code_id bigint,
  verified boolean not null default false,       -- repartidor aprobado
  data jsonb not null default '{}'::jsonb,        -- direcciones, tarjetas (solo marca y últimos 4)
  created_at timestamptz not null default now()
);
create unique index profiles_rep_nombre on public.profiles(lower(nombre)) where role='repartidor';

-- ===== tiendas y productos =====
create table public.stores(
  id bigint generated by default as identity primary key,
  cat text not null check (cat in ('abarrotes','farmacia')),
  n text not null, tipo text default '', col text default '', hor text default '',
  act boolean not null default true, ej boolean not null default false,
  extra jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.profiles add constraint profiles_store_fk foreign key (store_id) references public.stores(id) on delete set null;

create table public.products(
  id bigint generated by default as identity primary key,
  store_id bigint not null references public.stores(id) on delete cascade,
  n text not null, pres text default '', sec text default '', e text default '',
  p numeric(10,2) not null default 0,          -- precio al cliente
  disp boolean not null default true,
  stk integer,                                 -- null = sin control de existencias
  ord integer not null default 0,
  ej boolean not null default false,
  extra jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create index on public.products(store_id);
-- precio de compra (dato sensible): solo dueño/directivo y la tienda dueña del producto
create table public.product_costs(
  product_id bigint primary key references public.products(id) on delete cascade,
  store_id bigint not null references public.stores(id) on delete cascade,
  pc numeric(10,2) not null default 0,
  pc_est boolean not null default false,
  updated_at timestamptz not null default now()
);
create index on public.product_costs(store_id);

create table public.tablet_codes(
  id bigint generated by default as identity primary key,
  store_id bigint not null references public.stores(id) on delete cascade,
  code_hash text not null,
  act boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  por text, created_at timestamptz not null default now(), last_used timestamptz,
  fails int not null default 0, locked_until timestamptz
);
create index on public.tablet_codes(store_id);

create table public.settings(key text primary key, value jsonb not null, updated_at timestamptz default now());
create table private.secrets(key text primary key, value text not null, used_at timestamptz);

-- ===== pedidos =====
create table public.orders(
  id bigint generated by default as identity (start with 2001) primary key,
  cat text not null,
  store_id bigint references public.stores(id) on delete set null,
  client_id uuid references auth.users(id) on delete set null,
  src text not null default 'cuenta',
  rep_id uuid references auth.users(id) on delete set null,
  rep_name text not null default '',
  st int not null default 0,
  cancel boolean not null default false,
  zona int not null default 0,
  fee numeric(10,2) not null default 0,
  pago text not null default 'efectivo',
  pct numeric(5,2),
  cobrado boolean not null default false,
  det jsonb not null default '{}'::jsonb,   -- sin precios: tienda, notas, extra (texto), receta, de/a/tam
  wf jsonb not null default '{}'::jsonb,    -- flujo: ts, prep, recog, tacc, leido, cancelT, d
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index on public.orders(client_id); create index on public.orders(rep_id); create index on public.orders(store_id);
-- datos privados del pedido (contacto del cliente, montos): solo vía funciones
create table public.order_private(
  order_id bigint primary key references public.orders(id) on delete cascade,
  nombre text, tel text, dir text, senas text, email text,
  paga_con numeric(10,2) default 0, tarj jsonb, extra_est numeric(10,2) default 0,
  cobrado_monto numeric(10,2), compra jsonb, nota jsonb,
  guest_token_hash text
);
create table public.order_items(
  order_id bigint not null references public.orders(id) on delete cascade,
  idx int not null,
  pid bigint, n text not null, pres text default '', q int not null check (q between 1 and 99),
  p numeric(10,2) not null default 0,     -- precio cliente al pedir
  pc numeric(10,2),                       -- precio de compra al pedir (sensible)
  state jsonb not null default '{}'::jsonb, -- quit, na, res, surt
  primary key(order_id, idx)
);
create table public.order_events(
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  kind text not null, st int, by_role text, by_id uuid,
  created_at timestamptz not null default now()
);
create index on public.order_events(order_id);
create table public.messages(
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  de text not null, who text default '', kind text, txt text not null default '',
  cli boolean not null default false, extra jsonb not null default '{}'::jsonb,
  t bigint not null, sender uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(order_id, t, de)
);

-- ===== administración =====
create table public.complaints(id bigint primary key, order_id bigint references public.orders(id) on delete set null, client_id uuid references auth.users(id) on delete set null, data jsonb not null, updated_at timestamptz default now());
create table public.sanctions(key text primary key, data jsonb not null, updated_at timestamptz default now(), by_id uuid);
create table public.audit_log(id bigint generated by default as identity primary key, key text, data jsonb not null, actor uuid, created_at timestamptz default now());
create table public.repartidor_registrations(nombre text primary key, user_id uuid references auth.users(id) on delete cascade, data jsonb not null, updated_at timestamptz default now());
create table public.bank_accounts(rep_name text primary key, user_id uuid references auth.users(id) on delete cascade, data jsonb not null, updated_at timestamptz default now());
create table public.payouts(key text primary key, rep_name text not null, data jsonb not null, updated_at timestamptz default now());
create table public.cash_deposits(id bigint primary key, rep_name text not null, data jsonb not null);
create table public.store_credit_ledger(store_id bigint primary key references public.stores(id) on delete cascade, data jsonb not null, updated_at timestamptz default now());
create table public.store_requests(id bigint primary key, store_id bigint references public.stores(id) on delete cascade, data jsonb not null);
create table public.price_changes(id bigint primary key, store_id bigint references public.stores(id) on delete cascade, data jsonb not null);
create table public.admin_notes(key text primary key, data jsonb not null);
create index on public.complaints(order_id); create index on public.complaints(client_id);
create index on public.repartidor_registrations(user_id); create index on public.bank_accounts(user_id);
create index on public.store_requests(store_id); create index on public.price_changes(store_id);
create index on public.order_events(by_id); create index on public.messages(sender);
create index on public.tablet_codes(created_by); create index on public.profiles(store_id);
