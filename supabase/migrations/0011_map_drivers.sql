-- Mapa: ubicación de tiendas, ubicación de repartidores (solo dueño/directivo) y alertas "pedido en tienda"
alter table public.stores add column if not exists lat double precision, add column if not exists lng double precision;
alter table public.store_activation_requests add column if not exists lat double precision, add column if not exists lng double precision;

create table public.driver_locations(
  driver_id uuid primary key references auth.users(id) on delete cascade,
  lat double precision not null, lng double precision not null, accuracy double precision,
  available boolean not null default true, updated_at timestamptz not null default now()
);
alter table public.driver_locations enable row level security;
revoke all on public.driver_locations from anon, authenticated;
grant select on public.driver_locations to authenticated;
create policy dloc_admin on public.driver_locations for select to authenticated using ((select private.is_admin()));

create table public.driver_alerts(
  id bigint generated by default as identity primary key,
  driver_id uuid not null references auth.users(id) on delete cascade,
  store_id bigint references public.stores(id) on delete set null,
  order_id bigint references public.orders(id) on delete set null,
  message text not null default '',
  status text not null default 'enviada' check (status in ('enviada','vista','aceptada','rechazada')),
  note text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index on public.driver_alerts(driver_id); create index on public.driver_alerts(store_id);
create index on public.driver_alerts(order_id); create index on public.driver_alerts(created_by);
alter table public.driver_alerts enable row level security;
revoke all on public.driver_alerts from anon, authenticated;
grant select on public.driver_alerts to authenticated;
create policy dalert_sel on public.driver_alerts for select to authenticated using ((select private.is_admin()) or driver_id=(select auth.uid()));

-- repartidor: compartir / dejar de compartir ubicación
create or replace function public.update_my_location(p_lat double precision, p_lng double precision, p_acc double precision default null) returns void language plpgsql security definer set search_path='' as $$
begin
  if private.my_role()<>'repartidor' then raise exception 'Solo repartidores'; end if;
  if p_lat is null or p_lng is null or p_lat not between -90 and 90 or p_lng not between -180 and 180 then raise exception 'Ubicación no válida'; end if;
  insert into public.driver_locations(driver_id,lat,lng,accuracy,available,updated_at) values(auth.uid(),p_lat,p_lng,p_acc,true,now())
  on conflict (driver_id) do update set lat=excluded.lat,lng=excluded.lng,accuracy=excluded.accuracy,available=true,updated_at=now();
end $$;
create or replace function public.stop_sharing_location() returns void language sql security definer set search_path='' as
$$ delete from public.driver_locations where driver_id=(select auth.uid()) $$;

-- dueño/directivo: repartidores con ubicación
create or replace function public.get_driver_locations() returns jsonb language plpgsql stable security definer set search_path='' as $$
begin
  if not private.is_admin() then raise exception 'Solo dueño o directivo'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id',l.driver_id,'nombre',p.nombre,'lat',l.lat,'lng',l.lng,'acc',l.accuracy,
    't',(extract(epoch from l.updated_at)*1000)::bigint,'verified',p.verified,
    'activos',(select count(*) from public.orders o where o.rep_id=l.driver_id and not o.cancel and o.st < case when o.cat='paquetes' then 3 else 4 end))
    order by p.nombre) from public.driver_locations l join public.profiles p on p.id=l.driver_id and p.role='repartidor' where l.available),'[]');
end $$;

create or replace function public.set_store_location(p_store bigint, p_lat double precision, p_lng double precision) returns void language plpgsql security definer set search_path='' as $$
begin
  if not private.is_admin() then raise exception 'Solo dueño o directivo'; end if;
  if p_lat is not null and (p_lat not between -90 and 90 or p_lng not between -180 and 180) then raise exception 'Ubicación no válida'; end if;
  update public.stores set lat=p_lat,lng=p_lng,updated_at=now() where id=p_store;
  perform private.audit('tienda:'||(select n from public.stores where id=p_store),'Ubicación de la tienda actualizada');
end $$;

create or replace function public.send_driver_alert(p_driver uuid, p_store bigint, p_order bigint, p_msg text default '') returns bigint language plpgsql security definer set search_path='' as $$
declare o public.orders; nid bigint;
begin
  if not private.is_admin() then raise exception 'Solo dueño o directivo'; end if;
  if not exists(select 1 from public.profiles where id=p_driver and role='repartidor' and verified) then raise exception 'Repartidor no aprobado'; end if;
  if p_order is not null then
    select * into o from public.orders where id=p_order;
    if o.id is null or o.store_id is distinct from p_store then raise exception 'El pedido no es de esa tienda'; end if;
    if o.cancel or o.rep_id is not null then raise exception 'El pedido ya tiene repartidor o fue cancelado'; end if;
  end if;
  if (select count(*) from public.driver_alerts where created_by=auth.uid() and created_at>now()-interval '1 minute')>=20 then raise exception 'Demasiadas alertas seguidas'; end if;
  insert into public.driver_alerts(driver_id,store_id,order_id,message,created_by) values(p_driver,p_store,p_order,left(coalesce(p_msg,''),300),auth.uid()) returning id into nid;
  return nid;
end $$;

-- repartidor responde: vista / aceptada (asigna si sigue libre) / rechazada
create or replace function public.respond_driver_alert(p_id bigint, p_status text) returns jsonb language plpgsql security definer set search_path='' as $$
declare a public.driver_alerts; o public.orders; nm text := private.my_name();
begin
  select * into a from public.driver_alerts where id=p_id and driver_id=auth.uid() for update;
  if a.id is null then raise exception 'Alerta no encontrada'; end if;
  if p_status not in ('vista','aceptada','rechazada') then raise exception 'Estado no válido'; end if;
  if a.status in ('aceptada','rechazada') then return jsonb_build_object('status',a.status); end if;
  if p_status='aceptada' and a.order_id is not null then
    select * into o from public.orders where id=a.order_id for update;
    if o.cancel or (o.rep_id is not null and o.rep_id<>auth.uid()) then
      update public.driver_alerts set status='rechazada',note='El pedido ya fue tomado por otro repartidor',updated_at=now() where id=p_id;
      raise exception 'El pedido ya fue tomado por otro repartidor';
    end if;
    if not private.rep_ok() then raise exception 'Tu registro no está aprobado o estás suspendido'; end if;
    if o.rep_id is null then
      update public.orders set rep_id=auth.uid(), rep_name=nm, updated_at=now() where id=o.id;
      insert into public.order_events(order_id,kind,st,by_role,by_id) values(o.id,'aceptado',o.st,'rep',auth.uid());
    end if;
  end if;
  if not (p_status='vista' and a.status<>'enviada') then
    update public.driver_alerts set status=p_status,updated_at=now() where id=p_id;
  end if;
  return jsonb_build_object('status',p_status,'order_id',a.order_id);
end $$;

-- activación de tienda: ubicación opcional y copiar al aprobar
create or replace function public.request_store_activation_loc(p_id bigint, p_lat double precision, p_lng double precision) returns void language sql security definer set search_path='' as
$$ update public.store_activation_requests set lat=p_lat,lng=p_lng where id=p_id and session_id=(select auth.uid()) and status='pendiente'
   and p_lat between -90 and 90 and p_lng between -180 and 180 $$;
create or replace function private.sreq_copy_loc() returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.status='aprobada' and new.store_id is not null and new.lat is not null then
    update public.stores set lat=coalesce(lat,new.lat), lng=coalesce(lng,new.lng) where id=new.store_id;
  end if; return new;
end $$;
create trigger sreq_copy_loc after update of status on public.store_activation_requests for each row execute function private.sreq_copy_loc();

do $$ declare f text; begin
  foreach f in array array['public.update_my_location(double precision,double precision,double precision)','public.stop_sharing_location()','public.get_driver_locations()',
    'public.set_store_location(bigint,double precision,double precision)','public.send_driver_alert(uuid,bigint,bigint,text)','public.respond_driver_alert(bigint,text)',
    'public.request_store_activation_loc(bigint,double precision,double precision)'] loop
    execute format('revoke all on function %s from public, anon', f); execute format('grant execute on function %s to authenticated', f);
  end loop;
end $$;
